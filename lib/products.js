const STORAGE_KEY = "toque_de_desejo_products_v1";

// Carregar catálogo (com sincronização de localStorage se estiver no browser)
export function getCatalog() {
  if (typeof window !== "undefined") {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn("Erro ao ler catálogo do localStorage", e);
    }
  }
  return INITIAL_PRODUCTS;
}

// Salvar catálogo modificado no localStorage
export function saveCatalog(products) {
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(products));
      // Disparar evento personalizado para sincronização instantânea entre componentes
      window.dispatchEvent(new Event("toque_catalog_updated"));
      return true;
    } catch (e) {
      console.error("Erro ao salvar catálogo no localStorage", e);
      return false;
    }
  }
  return false;
}

// Resetar catálogo para os padrões de fábrica
export function resetCatalog() {
  if (typeof window !== "undefined") {
    try {
      localStorage.removeItem(STORAGE_KEY);
      window.dispatchEvent(new Event("toque_catalog_updated"));
      return INITIAL_PRODUCTS;
    } catch (e) {
      console.error(e);
    }
  }
  return INITIAL_PRODUCTS;
}

// Obter produto por slug
export function getProductBySlug(slug, catalog = INITIAL_PRODUCTS) {
  if (!slug) return null;
  return catalog.find((p) => p.slug === slug || p.id === slug) || null;
}

// Obter produtos relacionados
export function getRelatedProducts(currentProduct, catalog = INITIAL_PRODUCTS, limit = 4) {
  if (!currentProduct) return [];
  const sameCategory = catalog.filter(
    (p) => p.id !== currentProduct.id && p.active && p.category === currentProduct.category
  );
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }
  const otherProducts = catalog.filter(
    (p) => p.id !== currentProduct.id && p.active && p.category !== currentProduct.category
  );
  return [...sameCategory, ...otherProducts].slice(0, limit);
}

// Formatar preço em R$ brasileiro
export function formatCurrency(value) {
  if (value === undefined || value === null || isNaN(value)) return "Sob consulta";
  return new Intl.NumberFormat("pt-BR", {
    style: "currency",
    currency: "BRL"
  }).format(value);
}

// Gerar mensagem de WhatsApp para produto individual
export function generateProductWhatsAppLink(product, whatsappNumber) {
  const priceText = product.price ? formatCurrency(product.price) : "a consultar";
  const message = `Olá, Toque de Desejo! Vi o produto *${product.name}* (${priceText}) no site e tenho interesse em realizar o pedido com discrição. Poderia me atender?`;
  return `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(message)}`;
}

// Gerar mensagem de WhatsApp para carrinho com múltiplos produtos
export function generateCartWhatsAppLink(items, totalPrice, whatsappNumber) {
  let message = `Olá, Toque de Desejo! Gostaria de finalizar meu pedido pelo site com discrição:\n\n🛒 *Meu Pedido:*`;
  items.forEach((item) => {
    message += `\n• ${item.quantity}x ${item.name} (${formatCurrency(item.price * item.quantity)})`;
  });
  message += `\n\n💰 *Total:* ${formatCurrency(totalPrice)}`;
  message += `\n💳 Gostaria de verificar as opções de pagamento (Pix / Cartão) e o envio discreto. Poderia me atender?`;
  return `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(message)}`;
}
